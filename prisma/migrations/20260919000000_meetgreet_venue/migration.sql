-- MeetGreet に venue (会場の正式名称) を足す (#109)
--
-- リアルミーグリの記事タイトルを `2026年8月1日 リアルミーグリ（幕張メッセ）` の形にする。
-- 既に公開している記事が会場名つきなので、それに合わせる。
--
-- label と使い分ける:
--   - label = 短い呼び分け (幕張 / 京都 / 通常 / 初限)。ドシエ名・X レポ収集名に使う。表に出ない
--   - venue = 会場の正式名称 (幕張メッセ)。記事タイトルに出る。オンラインでは使わない
-- 取り込んだリアルの回は label を初期値として入れ、画面で正式名称に直す。
--
-- nullable で既定値なし (= 未設定)。既存行は null のままで、オンラインの回は今後も null。
-- 手動 GRANT は不要 (新しいテーブルは無く、列の権限はテーブル単位で付いている)。
-- MeetGreet は保護テーブルだが列追加だけなので RLS ポリシーの変更も無い。
-- 本番は SQL を先に当ててからデプロイする (nullable 列なので旧コードは影響を受けない)。

-- AlterTable
ALTER TABLE "MeetGreet" ADD COLUMN     "venue" TEXT;
