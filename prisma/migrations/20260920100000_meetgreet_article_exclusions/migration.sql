-- MeetGreet に articleExclusions (記事に足さないと決めたもの) を足す (#134)
--
-- 追記モードは「記事の本文に無い = まだ足していない」としか判断できず、**人が意図的に
-- 消したものを区別できない**。実例: 2026-08-01 のファンのレポ 1 件が X 側で削除されたため
-- 人が記事から手で消したが、次の追記がそれを「増えた 1 行」として復活させようとした。
--
-- 外したものをここに覚えて、二度と提示しない。
-- 形式: `report:<正規化 URL>` / `asset:<assetId>` / `tiktok:<videoId>` / `quote:<ハッシュ>`
-- 除外は回ごとに独立 (同じツイートが別の回のドシエにあれば、そちらでは普通に出る)。
--
-- 既定値ありの列追加だけなので既存行への影響は無い。手動 GRANT も不要
-- (新しいテーブルは無く、列の権限はテーブル単位で付いている)。
-- MeetGreet は保護テーブルだが RLS ポリシーの変更も無い。
-- 本番は SQL を先に当ててからデプロイする (既定値があるので旧コードは影響を受けない)。

-- AlterTable
ALTER TABLE "MeetGreet" ADD COLUMN     "articleExclusions" JSONB NOT NULL DEFAULT '[]';
