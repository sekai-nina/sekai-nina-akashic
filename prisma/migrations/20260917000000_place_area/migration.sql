-- Place に area (聖地マップのエリア) を足す
--
-- 公開サイトの聖地マップは、場所を「東京」「横浜・川崎」「名古屋」のようなエリアで絞り込み、
-- 低ズームではエリア名でまとめて表示する。これまでエリアはサイト側のコードに座標の表
-- (中心＋半径) を持って導出していたが、表にない地域に聖地が増えるとコードを触る必要が
-- あるので、kind と同じく Akashic の場所を正にして人が付ける (自由文字列)。
-- 画面の入力欄には既存のエリア名を候補に出し、表記のブレを防ぐ。
--
-- nullable で既定値は無し。既存行は座標の表から導出した値を初期投入する。
-- 列追加のみで RLS ポリシーの変更は無い。手動 GRANT も不要 (列の権限はテーブル単位)。
-- 本番は SQL を先に当ててからデプロイする (nullable 列なので旧コードは影響を受けない)。

-- AlterTable
ALTER TABLE "Place" ADD COLUMN     "area" TEXT;
