/** 「優しい, 多彩な表現」のように複数入った trait を配列にする */
export function splitTraits(raw: string): string[] {
  return String(raw ?? "")
    .split(/[,、]/)
    .map((t) => t.trim())
    .filter(Boolean);
}

/** 1 語の表記ゆれを寄せる。表に無ければそのまま */
export function canonicalTrait(trait: string): string {
  const t = trait.trim();
  return TRAIT_ALIASES[t] ?? t;
}

/** trait 文字列全体を正規化する(分割 → 寄せる → 重複を落とす → ", " で結合) */
export function normalizeTrait(raw: string): string {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const t of splitTraits(raw)) {
    const c = canonicalTrait(t);
    if (seen.has(c)) continue;
    seen.add(c);
    out.push(c);
  }
  return out.join(", ");
}
