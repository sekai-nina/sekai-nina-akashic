/**
 * AI の本文を記事に入れる形に揃える (改行コード・行末の空白・末尾の改行)。
 * **出典に無い番号の `^[n]` は落とす** (AI が番号を作った / 画面から来た下書きが古い)。
 * 宛先の無い脚注を公開リポジトリに出さないため。事実の文は残る (人が出典を付け直す)
 */
export function normalizeAiBody(body: string, sourceCount: number): string {
  return (
    body
      .replace(/\r\n?/g, "\n")
      .replace(/\^\[(\d+)\]/g, (whole, n) => (Number(n) >= 1 && Number(n) <= sourceCount ? whole : ""))
      .replace(/[ \t]+$/gm, "")
      .trim() + "\n"
  );
}

/** 下書きのタグを記事に入れる形に (前後の空白・空・重複を除く) */
export function normalizeAiTags(tags: string[]): string[] {
  return [...new Set(tags.map((t) => t.trim()).filter((t) => t.length > 0))];
}
