/** 回ごとの追加指示を足した最終プロンプト */
export function buildSketchPrompt(extra: string): string {
  const trimmed = extra.trim();
  if (!trimmed) return SKETCH_PROMPT;
  return `${SKETCH_PROMPT}\n\n今回の追加指示（上記より優先）：\n${trimmed}`;
}
